/* RFC 5958 - a OneAsymmetricKey carrying a publicKey that does not belong to the privateKey has to be rejected instead of being silently ignored. */
static int s_mldsa_pkcs8_publickey_test(void)
{
   /* version 1, then the ML-DSA-44 algorithm identifier */
   static const unsigned char v1[] = { 0x02, 0x01, 0x01 };
   static const unsigned char algid[] = { 0x30, 0x0b, 0x06, 0x09, 0x60, 0x86, 0x48, 0x01,
                                          0x65, 0x03, 0x04, 0x03, 0x11 };
   /* privateKey holding the seed CHOICE, [0] IMPLICIT OCTET STRING of 32 bytes */
   static const unsigned char priv[] = {
      0x04, 0x22, 0x80, 0x20, 0x00, 0x01, 0x02, 0x03, 0x04, 0x05, 0x06, 0x07, 0x08, 0x09,
      0x0a, 0x0b, 0x0c, 0x0d, 0x0e, 0x0f, 0x10, 0x11, 0x12, 0x13, 0x14, 0x15, 0x16, 0x17,
      0x18, 0x19, 0x1a, 0x1b, 0x1c, 0x1d, 0x1e, 0x1f
   };
   mldsa_key key;
   unsigned char pk[1400], body[2048], der[2048];
   unsigned long pklen, n = 0, hl;

   /* without a publicKey the seed alone has to import, that gives us the expected key */
   XMEMCPY(body + n, v1, sizeof(v1));       n += sizeof(v1);
   XMEMCPY(body + n, algid, sizeof(algid)); n += sizeof(algid);
   XMEMCPY(body + n, priv, sizeof(priv));   n += sizeof(priv);
   der[0] = 0x30;
   der[1] = 0x81;
   der[2] = (unsigned char)n;
   XMEMCPY(der + 3, body, n);
   DO(mldsa_import_pkcs8(der, n + 3, NULL, &key));
   pklen = sizeof(pk);
   DO(mldsa_export_raw(pk, &pklen, PK_PUBLIC, &key));
   mldsa_free(&key);

   /* append publicKey as [1] IMPLICIT BIT STRING */
   body[n++] = 0x81;
   body[n++] = 0x82;
   body[n++] = (unsigned char)((pklen + 1) >> 8);
   body[n++] = (unsigned char)(pklen + 1);
   body[n++] = 0x00;
   XMEMCPY(body + n, pk, pklen); n += pklen;

   der[0] = 0x30;
   der[1] = 0x82;
   der[2] = (unsigned char)(n >> 8);
   der[3] = (unsigned char)n;
   hl = 4;
   XMEMCPY(der + hl, body, n);

   DO(mldsa_import_pkcs8(der, n + hl, NULL, &key));
   mldsa_free(&key);

   /* the very same structure with one bit flipped in publicKey must not import */
   der[hl + n - pklen / 2] ^= 0x01;
   SHOULD_FAIL_WITH(mldsa_import_pkcs8(der, n + hl, NULL, &key), CRYPT_INVALID_PACKET);

   return CRYPT_OK;
}

static int s_mldsa_key_is(const mldsa_key *key,
                          const unsigned char *sk, unsigned long sklen,
                          const unsigned char *pk, unsigned long pklen,
                          const char *what, int alg)
{
   unsigned char buf[5000];
   unsigned long buflen;

   buflen = sizeof(buf);
   DO(mldsa_export_raw(buf, &buflen, PK_PRIVATE, key));
   COMPARE_TESTVECTOR(buf, buflen, sk, sklen, what, alg);
   buflen = sizeof(buf);
   DO(mldsa_export_raw(buf, &buflen, PK_PUBLIC, key));
   COMPARE_TESTVECTOR(buf, buflen, pk, pklen, what, alg);
   return CRYPT_OK;
}

/* RFC 9881 - the PKCS#8 private key is a CHOICE of seed, expandedKey or both. A seed cannot be
   computed back from the expanded key, so only a key that has one can write seed and both. */
static int s_mldsa_privkey_format_test(int alg)
{
   static const enum ltc_oid_id oids[] = { LTC_OID_MLDSA_44, LTC_OID_MLDSA_65, LTC_OID_MLDSA_87 };
   mldsa_key key, other, imported;
   unsigned char seed[LTC_MLDSA_KEYGEN_SEED_BYTES], buf[LTC_MLDSA_KEYGEN_SEED_BYTES];
   unsigned char sk[5000], other_sk[5000], pk[2600];
   unsigned char der[8192], der2[8192];
   unsigned long seedlen, buflen, sklen, other_sklen, pklen, derlen, der2len;
   int prng_idx = find_prng("yarrow");

   XMEMSET(&key, 0, sizeof(key));
   XMEMSET(&other, 0, sizeof(other));
   XMEMSET(&imported, 0, sizeof(imported));

   DO(mldsa_make_key(&yarrow_prng, prng_idx, alg, &key));
   ENSURE(mldsa_has_seed(&key) == 1);
   ENSURE(mldsa_has_seed(NULL) == 0);

   seedlen = sizeof(seed);
   DO(mldsa_export_seed(seed, &seedlen, &key));
   ENSURE(seedlen == LTC_MLDSA_KEYGEN_SEED_BYTES);
   buflen = 1;
   SHOULD_FAIL_WITH(mldsa_export_seed(buf, &buflen, &key), CRYPT_BUFFER_OVERFLOW);
   ENSURE(buflen == LTC_MLDSA_KEYGEN_SEED_BYTES);

   sklen = sizeof(sk);
   DO(mldsa_export_raw(sk, &sklen, PK_PRIVATE, &key));
   pklen = sizeof(pk);
   DO(mldsa_export_raw(pk, &pklen, PK_PUBLIC, &key));

   /* expanding the exported seed gives back the same key and the same seed */
   DO(mldsa_make_key_from_seed(alg, seed, seedlen, &imported));
   ENSURE(mldsa_has_seed(&imported) == 1);
   buflen = sizeof(buf);
   DO(mldsa_export_seed(buf, &buflen, &imported));
   COMPARE_TESTVECTOR(buf, buflen, seed, seedlen, "ML-DSA seed round-trip", alg);
   DO(s_mldsa_key_is(&imported, sk, sklen, pk, pklen, "ML-DSA seed expansion", alg));
   mldsa_free(&imported);

   /* a raw expanded private key has no seed */
   DO(mldsa_import_raw(sk, sklen, PK_PRIVATE, alg, &imported));
   ENSURE(mldsa_has_seed(&imported) == 0);
   mldsa_free(&imported);

   /* a public key never has a seed */
   DO(mldsa_import_raw(pk, pklen, PK_PUBLIC, alg, &imported));
   ENSURE(mldsa_has_seed(&imported) == 0);
   buflen = sizeof(buf);
   SHOULD_FAIL_WITH(mldsa_export_seed(buf, &buflen, &imported), CRYPT_PK_NOT_PRIVATE);
   mldsa_free(&imported);

   /* the raw private export is the expanded key, whatever the key object holds */
   der2len = sizeof(der2);
   DO(mldsa_export(der2, &der2len, PK_PRIVATE, &key));
   COMPARE_TESTVECTOR(der2, der2len, sk, sklen, "ML-DSA raw private export", alg);
   der2len = sizeof(der2);
   DO(mldsa_export_ex(der2, &der2len, PK_PRIVATE, LTC_PQC_PRIVKEY_EXPANDED, &key));
   COMPARE_TESTVECTOR(der2, der2len, sk, sklen, "ML-DSA raw private export expanded", alg);
   der2len = sizeof(der2);
   SHOULD_FAIL_WITH(mldsa_export_ex(der2, &der2len, PK_PRIVATE, LTC_PQC_PRIVKEY_SEED, &key), CRYPT_INVALID_ARG);
   der2len = sizeof(der2);
   SHOULD_FAIL_WITH(mldsa_export_ex(der2, &der2len, PK_PRIVATE, LTC_PQC_PRIVKEY_BOTH, &key), CRYPT_INVALID_ARG);
   der2len = sizeof(der2);
   SHOULD_FAIL_WITH(mldsa_export_ex(der2, &der2len, PK_PUBLIC | PK_STD, LTC_PQC_PRIVKEY_SEED, &key), CRYPT_INVALID_ARG);

   /* seed: AUTO uses it whenever the key has one */
   derlen = sizeof(der);
   DO(mldsa_export_ex(der, &derlen, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_SEED, &key));
   der2len = sizeof(der2);
   DO(mldsa_export(der2, &der2len, PK_PRIVATE | PK_STD, &key));
   COMPARE_TESTVECTOR(der2, der2len, der, derlen, "ML-DSA PKCS#8 AUTO is seed", alg);
   DO(mldsa_import_pkcs8(der, derlen, NULL, &imported));
   ENSURE(mldsa_has_seed(&imported) == 1);
   DO(s_mldsa_key_is(&imported, sk, sklen, pk, pklen, "ML-DSA PKCS#8 seed", alg));
   mldsa_free(&imported);

   /* expandedKey: the imported key cannot get the seed back */
   derlen = sizeof(der);
   DO(mldsa_export_ex(der, &derlen, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_EXPANDED, &key));
   DO(mldsa_import_pkcs8(der, derlen, NULL, &imported));
   ENSURE(mldsa_has_seed(&imported) == 0);
   DO(s_mldsa_key_is(&imported, sk, sklen, pk, pklen, "ML-DSA PKCS#8 expandedKey", alg));
   buflen = sizeof(buf);
   SHOULD_FAIL_WITH(mldsa_export_seed(buf, &buflen, &imported), CRYPT_PK_INVALID_TYPE);
   der2len = sizeof(der2);
   SHOULD_FAIL_WITH(mldsa_export_ex(der2, &der2len, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_SEED, &imported), CRYPT_PK_INVALID_TYPE);
   der2len = sizeof(der2);
   SHOULD_FAIL_WITH(mldsa_export_ex(der2, &der2len, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_BOTH, &imported), CRYPT_PK_INVALID_TYPE);
   der2len = sizeof(der2);
   DO(mldsa_export(der2, &der2len, PK_PRIVATE | PK_STD, &imported));
   COMPARE_TESTVECTOR(der2, der2len, der, derlen, "ML-DSA PKCS#8 AUTO falls back", alg);
   mldsa_free(&imported);

   /* both */
   derlen = sizeof(der);
   DO(mldsa_export_ex(der, &derlen, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_BOTH, &key));
   DO(mldsa_import_pkcs8(der, derlen, NULL, &imported));
   ENSURE(mldsa_has_seed(&imported) == 1);
   DO(s_mldsa_key_is(&imported, sk, sklen, pk, pklen, "ML-DSA PKCS#8 both", alg));
   mldsa_free(&imported);

   /* a both encoding whose seed and expandedKey do not match must be rejected, in
      either direction, so build the two mismatched halves straight from a second key */
   DO(mldsa_make_key(&yarrow_prng, prng_idx, alg, &other));
   other_sklen = sizeof(other_sk);
   DO(mldsa_export_raw(other_sk, &other_sklen, PK_PRIVATE, &other));
   buflen = sizeof(buf);
   DO(mldsa_export_seed(buf, &buflen, &other));

   der2len = sizeof(der2);
   DO(pqc_export_privkey(der2, &der2len, oids[alg], seed, seedlen, other_sk, other_sklen));
   SHOULD_FAIL_WITH(mldsa_import_pkcs8(der2, der2len, NULL, &imported), CRYPT_INVALID_PACKET);

   der2len = sizeof(der2);
   DO(pqc_export_privkey(der2, &der2len, oids[alg], buf, buflen, sk, sklen));
   SHOULD_FAIL_WITH(mldsa_import_pkcs8(der2, der2len, NULL, &imported), CRYPT_INVALID_PACKET);

   mldsa_free(&other);

   mldsa_free(&key);
   return CRYPT_OK;
}

