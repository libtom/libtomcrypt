/* FIPS 204 5.4.1 - the external mu functions have to give the same result as the normal sign and verify calls. */
static int s_mldsa_mu_test(int alg)
{
   static const unsigned char msg[] = "external mu test message";
   static const unsigned char ctx[] = "ctx";
   mldsa_key key, pub;
   unsigned char mu[LTC_MLDSA_MU_BYTES], mu2[LTC_MLDSA_MU_BYTES];
   unsigned char rnd[LTC_MLDSA_RND_BYTES], pk[2600];
   unsigned char *sig, *sig2;
   unsigned long mulen, mu2len, pklen, siglen, sig2len, sig_sz;
   int stat, prng_idx = find_prng("yarrow");

   XMEMSET(&key, 0, sizeof(key));
   XMEMSET(&pub, 0, sizeof(pub));
   XMEMSET(rnd, 0x42, sizeof(rnd));

   DO(mldsa_get_sizes(alg, NULL, NULL, &sig_sz, NULL, NULL, NULL));
   sig = XMALLOC(sig_sz);
   sig2 = XMALLOC(sig_sz);
   ENSURE(sig != NULL && sig2 != NULL);

   DO(mldsa_make_key(&yarrow_prng, prng_idx, alg, &key));
   pklen = sizeof(pk);
   DO(mldsa_export_raw(pk, &pklen, PK_PUBLIC, &key));
   DO(mldsa_import_raw(pk, pklen, PK_PUBLIC, alg, &pub));

   /* mu only needs the public key */
   mulen = sizeof(mu);
   DO(mldsa_compute_mu(mu, &mulen, msg, sizeof(msg), ctx, sizeof(ctx) - 1, &key));
   ENSURE(mulen == LTC_MLDSA_MU_BYTES);
   mu2len = sizeof(mu2);
   DO(mldsa_compute_mu(mu2, &mu2len, msg, sizeof(msg), ctx, sizeof(ctx) - 1, &pub));
   COMPARE_TESTVECTOR(mu2, mu2len, mu, mulen, "ML-DSA mu from public key", alg);

   mu2len = 1;
   SHOULD_FAIL_WITH(mldsa_compute_mu(mu2, &mu2len, msg, sizeof(msg), ctx, sizeof(ctx) - 1, &key),
                    CRYPT_BUFFER_OVERFLOW);
   ENSURE(mu2len == LTC_MLDSA_MU_BYTES);
   mu2len = sizeof(mu2);
   SHOULD_FAIL_WITH(mldsa_compute_mu(mu2, &mu2len, msg, sizeof(msg), ctx, LTC_PQC_CTX_MAX_BYTES + 1uL, &key),
                    CRYPT_INVALID_ARG);

   /* signing through mu is the same operation as signing the message */
   siglen = sig_sz;
   DO(mldsa_sign_ex(msg, sizeof(msg), sig, &siglen, ctx, sizeof(ctx) - 1, rnd, sizeof(rnd), &key));
   sig2len = sig_sz;
   DO(mldsa_sign_ex_mu(mu, mulen, sig2, &sig2len, rnd, sizeof(rnd), &key));
   COMPARE_TESTVECTOR(sig2, sig2len, sig, siglen, "ML-DSA sign via external mu", alg);

   stat = 0;
   DO(mldsa_verify_mu(sig, siglen, mu, mulen, &stat, &pub));
   ENSURE(stat == 1);

   XMEMCPY(mu2, mu, mulen);
   mu2[0] ^= 1;
   stat = 1;
   DO(mldsa_verify_mu(sig, siglen, mu2, mulen, &stat, &pub));
   ENSURE(stat == 0);

   SHOULD_FAIL_WITH(mldsa_verify_mu(sig, siglen, mu, mulen - 1, &stat, &pub), CRYPT_INVALID_ARG);
   SHOULD_FAIL_WITH(mldsa_sign_ex_mu(mu, mulen - 1, sig2, &sig2len, rnd, sizeof(rnd), &key),
                    CRYPT_INVALID_ARG);

   /* an empty message with no context is allowed and is still bound by mu */
   mulen = sizeof(mu);
   DO(mldsa_compute_mu(mu, &mulen, NULL, 0, NULL, 0, &key));
   siglen = sig_sz;
   DO(mldsa_sign_ex_mu(mu, mulen, sig, &siglen, rnd, sizeof(rnd), &key));
   stat = 0;
   DO(mldsa_verify(sig, siglen, NULL, 0, NULL, 0, &stat, &pub));
   ENSURE(stat == 1);

   mldsa_free(&pub);
   mldsa_free(&key);
   XFREE(sig2);
   XFREE(sig);
   return CRYPT_OK;
}


/* mldsa_check_key() has to detect a key struct that a caller changed */
static int s_mldsa_check_key_test(int alg)
{
   mldsa_key key, pub;
   unsigned char pk[2600], der[8192];
   unsigned long pklen, derlen;
   int prng_idx = find_prng("yarrow");

   XMEMSET(&key, 0, sizeof(key));
   XMEMSET(&pub, 0, sizeof(pub));

   DO(mldsa_make_key(&yarrow_prng, prng_idx, alg, &key));
   DO(mldsa_check_key(&key));

   pklen = sizeof(pk);
   DO(mldsa_export_raw(pk, &pklen, PK_PUBLIC, &key));
   DO(mldsa_import_raw(pk, pklen, PK_PUBLIC, alg, &pub));
   DO(mldsa_check_key(&pub));

   /* a wrong key field is reported before any key material is expanded */
   key.sklen -= 1;
   SHOULD_FAIL_WITH(mldsa_check_key(&key), CRYPT_PK_INVALID_TYPE);
   key.sklen += 1;
   key.type = PK_PUBLIC;
   SHOULD_FAIL_WITH(mldsa_check_key(&key), CRYPT_PK_INVALID_TYPE);
   key.type = PK_PRIVATE;

   /* a public key that does not match the one rebuilt from the signing key */
   key.pk[0] ^= 1;
   SHOULD_FAIL_WITH(mldsa_check_key(&key), CRYPT_INVALID_PACKET);
   key.pk[0] ^= 1;

   /* tr, which follows rho and K in the signing key */
   key.sk[2 * LTC_MLDSA_KEYGEN_SEED_BYTES] ^= 1;
   SHOULD_FAIL_WITH(mldsa_check_key(&key), CRYPT_INVALID_PACKET);
   key.sk[2 * LTC_MLDSA_KEYGEN_SEED_BYTES] ^= 1;

   /* a seed that no longer expands to this key, the both export has to fail too */
   key.seed[0] ^= 1;
   SHOULD_FAIL_WITH(mldsa_check_key(&key), CRYPT_INVALID_PACKET);
   derlen = sizeof(der);
   SHOULD_FAIL_WITH(mldsa_export_ex(der, &derlen, PK_PRIVATE | PK_STD, LTC_PQC_PRIVKEY_BOTH, &key),
                    CRYPT_INVALID_PACKET);
   key.seed[0] ^= 1;
   DO(mldsa_check_key(&key));

   mldsa_free(&pub);
   mldsa_free(&key);
   return CRYPT_OK;
}

static void s_mldsa_try_import(const unsigned char *in, unsigned long inlen, int kind, int alg)
{
   mldsa_key key;
   int err;

   XMEMSET(&key, 0, sizeof(key));
   switch (kind) {
      case 0:  err = mldsa_import_raw(in, inlen, PK_PUBLIC, alg, &key); break;
      case 1:  err = mldsa_import_raw(in, inlen, PK_PRIVATE, alg, &key); break;
      case 2:  err = mldsa_import(in, inlen, &key); break;
      default: err = mldsa_import_pkcs8(in, inlen, NULL, &key); break;
   }
   /* anything an importer accepts has to pass the key check as well */
   if (err == CRYPT_OK) DO(mldsa_check_key(&key));
   mldsa_free(&key);
}

/* A deterministic replacement for fuzzing: every encoding a key can be read from is
   truncated, extended and bit flipped. Run it under ASan/UBSan to get the most out of it. */
static int s_mldsa_import_mutation_test(int alg)
{
   mldsa_key key;
   unsigned char enc[4][8192], buf[8300];
   static const int kinds[6] = { 0, 1, 2, 3, 3, 3 };
   const unsigned char *src[6];
   unsigned long lens[6], i, n, pos, step;
   int prng_idx = find_prng("yarrow");

   XMEMSET(&key, 0, sizeof(key));
   DO(mldsa_make_key(&yarrow_prng, prng_idx, alg, &key));

   lens[0] = sizeof(enc[0]);
   DO(mldsa_export_raw(enc[0], &lens[0], PK_PUBLIC, &key));
   lens[1] = sizeof(enc[1]);
   DO(mldsa_export_raw(enc[1], &lens[1], PK_PRIVATE, &key));
   lens[2] = sizeof(enc[2]);
   DO(mldsa_export(enc[2], &lens[2], PK_PUBLIC | PK_STD, &key));
   /* the three PKCS#8 private-key representations share one buffer, one at a time */
   for (i = 0; i < 3; i++) src[i] = enc[i];

   for (n = 0; n < 6; n++) {
      if (n >= 3) {
         static const enum ltc_pqc_privkey_format formats[3] = {
            LTC_PQC_PRIVKEY_SEED, LTC_PQC_PRIVKEY_EXPANDED, LTC_PQC_PRIVKEY_BOTH
         };
         lens[n] = sizeof(enc[3]);
         DO(mldsa_export_ex(enc[3], &lens[n], PK_PRIVATE | PK_STD, formats[n - 3], &key));
         src[n] = enc[3];
      }

      XMEMCPY(buf, src[n], lens[n]);
      s_mldsa_try_import(buf, lens[n], kinds[n], alg);

      /* truncation and extension */
      s_mldsa_try_import(buf, 0, kinds[n], alg);
      s_mldsa_try_import(buf, 1, kinds[n], alg);
      s_mldsa_try_import(buf, lens[n] / 2, kinds[n], alg);
      s_mldsa_try_import(buf, lens[n] - 1, kinds[n], alg);
      buf[lens[n]] = 0x00;
      s_mldsa_try_import(buf, lens[n] + 1, kinds[n], alg);

      /* one flipped byte at a time, spread over the whole encoding */
      step = lens[n] / 64 ? lens[n] / 64 : 1;
      for (pos = 0; pos < lens[n]; pos += step) {
         buf[pos] ^= 0x80;
         s_mldsa_try_import(buf, lens[n], kinds[n], alg);
         buf[pos] ^= 0x80;
      }
   }

   mldsa_free(&key);
   return CRYPT_OK;
}

